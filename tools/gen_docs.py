"""Regenerate docs/PERMISSIONS.md and docs/CIS_COVERAGE.md from the code, so the documentation cannot drift from the checks.
Run:  python tools/gen_docs.py     (tests/test_docs.py fails if the committed docs are out of date)
"""
import os
import re
import sys
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from entra_scan import metadata, permissions  # noqa: E402
from entra_scan.models import CHECKS  # noqa: E402

DOC = "https://learn.microsoft.com/en-us/graph/api/"


def permissions_md():
    out = ["# Permissions", "", "<!-- generated by tools/gen_docs.py - do not edit by hand -->", "",
           "The scanner is **read-only** and uses **Microsoft Graph application permissions only** (client-credentials sign-in).",
           "Nothing else is needed: no Azure RBAC role, no Exchange or Defender permission, and no write permission of any kind.", "",
           "## Grant these (then click *Grant admin consent*)", "", "| Permission | Why | Checks that use it |", "|---|---|---|"]
    for name, why, used in permissions.permission_table():
        out.append(f"| `{name}` | {why} | {', '.join(used)} |")
    out += ["", "## Endpoint-by-endpoint verification", "",
            "Each row was checked against the Microsoft Graph v1.0 documentation. *Least privileged* is the lowest permission Microsoft lists "
            "for application access; *Requested* is what this app asks for (a few endpoints share one broader permission to keep the list short).", "",
            "| Endpoint | Least privileged | Requested | Documentation | Verification note |", "|---|---|---|---|---|"]
    for ep, least, req, page, note in permissions.ENDPOINTS:
        out.append(f"| `{ep}` | `{least}` | `{req}` | [{page}]({DOC}{page}?view=graph-rest-1.0) | {note} |")
    out += ["", "## Not readable with an application permission", ""]
    for ep, why in permissions.NOT_AVAILABLE.items():
        out.append(f"* `{ep}` - {why}")
    out += ["", "## Licences", "",
            "* Conditional Access, sign-in activity, Identity Protection: Entra ID P1 / P2. Without them the affected checks report **SKIPPED**, never PASS.",
            "* PIM role settings and access reviews: Entra ID P2 or Entra ID Governance.", ""]
    return "\n".join(out)


def coverage_md():
    cov = defaultdict(list)
    for i, text in metadata.CIS_MAP.items():
        m = re.search(r"v5\.0\.0, ([\d.]+): (.*)", text)
        cov[m.group(1)].append((i, m.group(2)))
    key = lambda n: [int(x) for x in n.split(".")]
    out = ["# CIS Microsoft 365 Foundations Benchmark v5.0.0 - Entra ID coverage", "",
           "<!-- generated by tools/gen_docs.py - do not edit by hand -->", "",
           "AUTO = evaluated by the scan (PASS / WARN / FAIL). MANUAL = Microsoft Graph cannot read the setting with an app-only token, so the "
           "report lists it as a **MANUAL** item with exact portal steps; it is never counted as passed.", "",
           f"**{len(cov)} controls** are mapped. {sum(1 for c in cov.values() if all(i.startswith('MAN-') for i, _ in c))} are manual.", "",
           "| CIS | Control | Type | Check ID(s) |", "|---|---|---|---|"]
    for num in sorted(cov, key=key):
        ids = cov[num]
        kind = "MANUAL" if all(i.startswith("MAN-") for i, _ in ids) else "AUTO"
        out.append(f"| {num} | {ids[0][1]} | {kind} | {', '.join(i for i, _ in ids)} |")
    extra = sorted(f.__name__ for _, f in CHECKS)
    out += ["", f"Beyond CIS the scan also runs best-practice checks (applications, consent grants, stale users, devices, cross-tenant access, "
                f"identity protection). {len(extra)} check functions in total.", ""]
    return "\n".join(out)


if __name__ == "__main__":
    for name, text in (("PERMISSIONS.md", permissions_md()), ("CIS_COVERAGE.md", coverage_md())):
        with open(os.path.join(ROOT, "docs", name), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print("wrote docs/" + name)
